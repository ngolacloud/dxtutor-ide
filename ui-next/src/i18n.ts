const STORE = "dxnext-locale";

function stored(): Locale {
  try {
    const v = localStorage.getItem(STORE);
    return v === "en" || v === "ptAO" ? v : "ptAO";
  } catch {
    return "ptAO";
  }
}

let locale: Locale = stored();
const listeners = new Set<() => void>();

export function getLocale(): Locale {
  return locale;
}

/** Muda a locale, persiste e repinta todos os assinantes + os textos estáticos. */
export function setLocale(l: Locale): void {
  if (l === locale) return;
  locale = l;
  try { localStorage.setItem(STORE, l); } catch { /* storage indisponível */ }
  applyStatic();
  listeners.forEach((cb) => cb());
}

export function onLocaleChange(cb: () => void): void {
  listeners.add(cb);
}

/** Tradução com parâmetros: t("toast.saved", {files: "a.md"}). Chave em falta → a própria chave
 * (falha visível, nunca inglês silencioso). */
export function t(key: string, params?: Record<string, string | number>): string {
  let s = STRINGS[locale][key] ?? STRINGS.en[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Preenche os textos estáticos do index.html: [data-i18n] → textContent,
 * [data-i18n-title] → title, [data-i18n-ph] → placeholder. Também afina o lang do documento. */
export function applyStatic(root: ParentNode = document): void {
  document.documentElement.lang = locale === "ptAO" ? "pt-AO" : "en";
  root.querySelectorAll<HTMLElement>("[data-i18n]").forEach((el) => {
    el.textContent = t(el.dataset.i18n ?? "");
  });
  root.querySelectorAll<HTMLElement>("[data-i18n-title]").forEach((el) => {
    el.title = t(el.dataset.i18nTitle ?? "");
  });
  root.querySelectorAll<HTMLInputElement>("[data-i18n-ph]").forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh ?? "");
  });
}
