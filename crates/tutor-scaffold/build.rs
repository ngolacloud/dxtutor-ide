//! Embeds the project templates (`templates/projects/<name>/…`, copied from Delonix by
//! `scripts/sync-delonix-templates.sh`) so «New Project» needs no files next to the binary — the same
//! way `delonix init -t` embeds them. Each file goes in with `include_str!`; the executable bit travels
//! with it (a generated `scripts/smoke.sh` must come out runnable).

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

fn main() {
    let root = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap())
        .join("../../templates/projects")
        .canonicalize()
        .expect("templates/projects (run scripts/sync-delonix-templates.sh)");
    println!("cargo::rerun-if-changed={}", root.display());
    let mut names: Vec<PathBuf> = std::fs::read_dir(&root)
        .unwrap()
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.is_dir())
        .collect();
    names.sort();
    let mut out = String::from(
        "// @generated by build.rs — do not edit.\n\
         /// `(relative path, content, executable)`.\n\
         pub(crate) type TemplateFile = (&'static str, &'static str, bool);\n\
         pub(crate) static TEMPLATES: &[(&str, &[TemplateFile])] = &[\n",
    );
    for dir in &names {
        let name = dir.file_name().unwrap().to_string_lossy().to_string();
        let mut files = vec![];
        walk(dir, dir, &mut files);
        files.sort();
        writeln!(out, "    ({name:?}, &[").unwrap();
        for (rel, abs, exec) in files {
            writeln!(
                out,
                "        ({rel:?}, include_str!({:?}), {exec}),",
                abs.display().to_string()
            )
            .unwrap();
        }
        writeln!(out, "    ]),").unwrap();
    }
    out.push_str("];\n");
    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("templates.rs");
    std::fs::write(dest, out).unwrap();
}

fn walk(base: &Path, dir: &Path, out: &mut Vec<(String, PathBuf, bool)>) {
    for e in std::fs::read_dir(dir).unwrap().flatten() {
        let p = e.path();
        if p.is_dir() {
            walk(base, &p, out);
        } else {
            let rel = p
                .strip_prefix(base)
                .unwrap()
                .to_string_lossy()
                .replace('\\', "/");
            out.push((rel, p.clone(), executable(&p)));
        }
    }
}

#[cfg(unix)]
fn executable(p: &Path) -> bool {
    use std::os::unix::fs::PermissionsExt;
    std::fs::metadata(p)
        .map(|m| m.permissions().mode() & 0o111 != 0)
        .unwrap_or(false)
}

#[cfg(not(unix))]
fn executable(_: &Path) -> bool {
    false
}
